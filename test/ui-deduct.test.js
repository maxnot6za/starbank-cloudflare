// หักดาว (หน้าจอ): แตะการ์ดลูก → การ์ดใหญ่ → หักดาว + ภารกิจแก้ตัว → ลูกเห็นป๊อปอัปทันที → ส่งแก้ตัว → ผู้ปกครองอนุมัติ → ได้ดาวคืน
const { chromium } = require('playwright');
const { seedFamily, P1, C } = require('./lib/fixture.js');
const { start, sessionFor } = require('./lib/mf.js');
const routes = require(process.env.SB_ROUTES || './lib/routes.js');
let fails = 0;
const ok = (c, l, x) => { console.log(c ? '✓' : '✗', l, x === undefined ? '' : JSON.stringify(x).slice(0, 300)); if (!c) fails++; };
(async () => {
  const { mf, db } = await start({ port: 0 }); await seedFamily(db);
  const today = new Date(Date.now() + 7 * 3600000).toISOString().slice(0, 10);
  await db.prepare("UPDATE Members SET quest_seen = ?, news_seen = 99, tree_seen = '9999'").bind(today).run();
  const base = String(await mf.ready).replace(/\/$/, ''); const br = await chromium.launch(), errors = [];
  const open = async id => { const ctx = await br.newContext({ viewport: { width: 390, height: 844 } });
    await ctx.addCookies([{ name: 'sb_s', value: await sessionFor(db, id), url: base }]);
    await ctx.addInitScript(() => { try { localStorage.setItem('sb_ui2', '1'); } catch (e) {} });
    const p = await ctx.newPage(); p.on('pageerror', e => errors.push(e.message)); await routes(p); await p.goto(base + '/'); return p; };
  const par = await open(P1);
  await par.waitForSelector('.u2-slide[data-kid]', { timeout: 15000 }); await par.waitForTimeout(1200);
  await par.evaluate(() => { while (MODAL.stack.length) MODAL.stack.pop(); closeModal(); }); await par.waitForTimeout(400);
  ok(!(await par.locator('.u2-slide[data-kid] .u2-goal button').count()), 'การ์ดลูกไม่มีปุ่มของขวัญ/QR แล้ว');
  await par.click('.u2-slide[data-kid]'); await par.waitForTimeout(1200);
  ok(await par.isVisible('.kc.open') && await par.locator('.kc-a').count() === 3, 'แตะการ์ด → การ์ดใหญ่ + 3 ปุ่ม');
  const bal0 = Number(await par.textContent('#kc-bal'));
  await par.mouse.click(10, 10); await par.waitForTimeout(900);
  ok(!(await par.locator('.kc').count()) && await par.isVisible('.u2-slide[data-kid]'), 'แตะพื้นที่เบลอ → ปิด การ์ดเดิมกลับมา');
  await par.click('.u2-slide[data-kid]'); await par.waitForTimeout(1200);
  await par.click('.kc-a.minus'); await par.waitForTimeout(500);
  await par.click('#dd-go'); await par.waitForTimeout(400);
  ok(await par.isVisible('#dd-reason') && !(await db.prepare('SELECT * FROM Deductions').first()), 'ไม่ใส่เหตุผล → ยังไม่หัก');
  await par.fill('#dd-reason', 'พูดไม่สุภาพกับพี่'); await par.click('#dd-stars + .u-chip');
  for (let i = 0; i < 20; i++) await par.click('#dd-stars + .u-chip');
  ok(Number(await par.textContent('#dd-stars')) === bal0, 'เพิ่มจำนวนได้ไม่เกินดาวที่ลูกมี', await par.textContent('#dd-stars'));
  await par.evaluate(() => { window.__dd.stars = 2; document.getElementById('dd-stars').textContent = 2; });
  await par.fill('#dd-title', 'ขอโทษพี่'); await par.click('#dd-time .u-chip:has-text("1 ชม.")');
  await par.click('#dd-go'); await par.waitForSelector('.dd-done', { timeout: 5000 });
  ok(Number(await par.textContent('#kc-bal')) === bal0 - 2, 'หักแล้ว ตัวเลขในการ์ดลด 2', await par.textContent('#kc-bal'));
  const row = await db.prepare('SELECT * FROM Deductions').first();
  ok(row.stars === 2 && row.reason === 'พูดไม่สุภาพกับพี่' && row.fix_title === 'ขอโทษพี่' && Math.abs(new Date(row.fix_until) - Date.now() - 3600000) < 120000, 'บันทึก: 2 ดาว + เหตุผล + แก้ตัว 1 ชม.', row);
  await par.click('text=เสร็จแล้ว'); await par.waitForTimeout(900);

  const kid = await open(C);
  await kid.waitForSelector('.ded-pop', { timeout: 15000 });
  const pop = await kid.textContent('.ded-pop');
  ok(/−2/.test(pop) && /พูดไม่สุภาพกับพี่/.test(pop) && /ขอโทษพี่/.test(pop), 'ลูกเห็นป๊อปอัปทันที: −2 + เหตุผล + ภารกิจแก้ตัว');
  await kid.click('.ded-pop .dq-btn.g'); await kid.waitForTimeout(800);
  ok(!!(await db.prepare('SELECT seen_at FROM Deductions').first()).seen_at, 'ปิดแล้ว จำว่าเห็นแล้ว');
  await kid.evaluate(() => { while (MODAL.stack.length) MODAL.stack.pop(); closeModal(); }); await kid.waitForTimeout(300);
  ok(await kid.isVisible('.k2-fixc') && /เหลือ \d+ นาที/.test(await kid.textContent('.k2-fixc')), 'การ์ดภารกิจแก้ตัว + เวลาที่เหลือ', await kid.textContent('.k2-fixc'));
  await kid.click('.k2-fixc button'); await kid.waitForTimeout(1500);
  ok(/รออนุมัติ/.test(await kid.textContent('.k2-fixc')), 'ส่งแล้ว → รออนุมัติ');

  await par.waitForSelector('.u2-pr.fix', { timeout: 8000 });
  ok(/ขอโทษพี่/.test(await par.textContent('.u2-pr.fix')), 'ผู้ปกครองเห็นภารกิจแก้ตัวในกล่องรออนุมัติ');
  await par.click('.u2-pr.fix .ok'); await par.waitForTimeout(1500);
  ok((await db.prepare('SELECT fix_status FROM Deductions').first()).fix_status === 'done', 'อนุมัติ → ได้ดาวคืน');
  await kid.waitForTimeout(1500);
  ok(!(await kid.locator('.k2-fixc').count()), 'ลูก: การ์ดแก้ตัวหายไป');
  await kid.evaluate(() => childNav('history')); await kid.waitForTimeout(800);
  const h = await kid.textContent('#child-history-list');
  ok(/โดนหักดาว/.test(h) && /แก้ตัวสำเร็จ/.test(h), 'ประวัติลูก: หักดาว + แก้ตัวสำเร็จ');
  ok(!errors.length, 'ไม่มี JS error', errors);
  await br.close(); await mf.dispose(); console.log(fails ? fails + ' ไม่ผ่าน' : 'ผ่านทั้งหมด'); process.exit(fails ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
