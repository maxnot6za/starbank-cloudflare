// สัตว์เลี้ยง (ตัวละครประเภทที่ 4): ซื้อ 20 ดาวม่วง → เข้าห้องเอง · พาออก/เข้า (สูงสุด 2) · เด็กจัดไม่ได้ · เดินในแถบห้อง
const { chromium } = require('playwright');
const { seedFamily, FAM, P1, C } = require('./lib/fixture.js');
const { start, call, sessionFor } = require('./lib/mf.js');
const routes = require(process.env.SB_ROUTES || './lib/routes.js');
const OUT = require('os').tmpdir() + '/starbank-shots/'; require('fs').mkdirSync(OUT, { recursive: true });
let fails = 0;
const ok = (c, l, x) => { console.log(c ? '✓' : '✗', l, x === undefined ? '' : JSON.stringify(x).slice(0, 300)); if (!c) fails++; };
(async () => {
  const { mf, db } = await start({ port: 0 });
  await seedFamily(db);
  const today = new Date(Date.now() + 7 * 3600000).toISOString().slice(0, 10);
  await db.prepare('UPDATE Members SET quest_seen = ?, tree_seen = ?').bind(today, '9999').run();
  await db.prepare('UPDATE Families SET purple = 60 WHERE family_id = ?').bind(FAM).run();
  let r = await call(mf, 'getShop', P1);
  const pet = r.value.items.find(i => i.kind === 'pet');
  ok(pet && pet.id === 'pet_dino' && pet.price === 20 && pet.sprite === 'petdino', 'ร้านมีไดโนจิ๋ว 20 ดาวม่วง', pet);
  r = await call(mf, 'buyItem', C, 'pet_dino'); ok(!r.ok, 'เด็กซื้อไม่ได้');
  r = await call(mf, 'buyItem', P1, 'pet_dino');
  ok(r.ok && r.value.paid === 10, 'ซื้อชิ้นแรกลด 50% → 10', r.value && r.value.paid);
  let st = (await call(mf, 'getShop', P1)).value.stage;
  ok(st.pets.length === 1 && st.pets[0].sprite === 'petdino' && st.petMax === 2, 'ซื้อแล้วเข้าห้องเอง', st.pets);
  r = await call(mf, 'setPets', C, '[]'); ok(!r.ok, 'เด็กพาออกไม่ได้');
  r = await call(mf, 'setPets', P1, '[]'); ok(r.ok && !r.value.stage.pets.length, 'ผู้ปกครองพาออกได้');
  r = await call(mf, 'setPets', P1, '["pet_dino","pet_dino","pet_dino"]'); ok(!r.ok, 'เกิน 2 ตัวไม่ได้');
  r = await call(mf, 'setPets', P1, '["dino_kid"]'); ok(!r.ok, 'ใส่ของที่ไม่ใช่สัตว์เลี้ยงไม่ได้');
  r = await call(mf, 'setPets', P1, '["pet_dino"]'); ok(r.ok && r.value.stage.pets.length === 1, 'พาเข้าห้องอีกครั้ง');
  const d = (await call(mf, 'getChildDashboard', C)).value;
  ok(d && d.stage && d.stage.pets.length === 1, 'หน้าเด็กเห็นสัตว์เลี้ยงในห้อง');

  const base = String(await mf.ready).replace(/\/$/, '');
  const browser = await chromium.launch(), errors = [];
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  await ctx.addCookies([{ name: 'sb_s', value: await sessionFor(db, P1), url: base }]);
  const p = await ctx.newPage(); await routes(p); p.on('pageerror', e => errors.push(e.message)); await p.goto(base + '/');
  await p.waitForSelector('#avatar-strip.on', { timeout: 15000 });
  ok(await p.waitForFunction(() => document.querySelectorAll('#avatar-strip canvas, #avatar-strip .sa-actor, #avatar-strip [data-actor]').length > 0 || document.querySelector('#avatar-strip').children.length > 2, null, { timeout: 8000 }).then(() => true, () => false), 'ไดโนจิ๋วเดินในแถบห้อง');
  ok(!(await p.isVisible('#avatar-strip .strip-sign')), 'มีสัตว์เลี้ยงแล้วไม่ขึ้นป้ายชวนซื้อตัวละคร');
  await p.waitForTimeout(2500); await p.screenshot({ path: OUT + 'p1-strip-pet.png' });
  await p.click('#pnav-shop'); await p.click('.shop-tabs button:has-text("สัตว์เลี้ยง")'); await p.waitForTimeout(1200);
  ok(await p.isVisible('#screen-parent-shop .shop-item >> text=ไดโนจิ๋ว'), 'แท็บสัตว์เลี้ยงในร้าน');
  await p.screenshot({ path: OUT + 'p2-shop-pet.png' });
  await p.click('#screen-parent-shop .shop-item'); await p.waitForSelector('#modal-content button:has-text("พาออกจากห้อง")');
  await p.waitForTimeout(800); await p.screenshot({ path: OUT + 'p3-pet-item.png' });
  await p.click('#modal-content button:has-text("พาออกจากห้อง")'); await p.waitForTimeout(1200);
  ok(!JSON.parse((await db.prepare('SELECT stage FROM Families').first()).stage).pets.length, 'กดพาออกจากห้อง → บันทึก');
  ok(!errors.length, 'ไม่มี JS error', errors);
  await browser.close(); await mf.dispose();
  console.log(fails ? fails + ' ไม่ผ่าน' : 'ผ่านทั้งหมด'); process.exit(fails ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
