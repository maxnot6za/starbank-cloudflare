// มีอะไรใหม่ v7: การ์ดฟีเจอร์ + คลิป + ลองเลย → ทัวร์หักดาว (ไม่หักจริง) → แสตมป์ลองแล้ว · ปิดได้โดยไม่ต้องลอง
const { chromium } = require('playwright');
const { seedFamily, P1 } = require('./lib/fixture.js');
const { start, sessionFor } = require('./lib/mf.js');
const routes = require(process.env.SB_ROUTES || './lib/routes.js');
const OUT = process.env.SHOT_DIR || '';
let fails = 0;
const ok = (c, l, x) => { console.log(c ? '✓' : '✗', l, x === undefined ? '' : JSON.stringify(x).slice(0, 300)); if (!c) fails++; };
(async () => {
  const { mf, db } = await start({ port: 0 }); await seedFamily(db);
  const today = new Date(Date.now() + 7 * 3600000).toISOString().slice(0, 10);
  await db.prepare("UPDATE Members SET quest_seen = ?, news_seen = 6, tree_seen = '9999'").bind(today).run();
  const base = String(await mf.ready).replace(/\/$/, ''); const br = await chromium.launch(), errors = [];
  const ctx = await br.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: OUT ? 2 : 1 });
  await ctx.addCookies([{ name: 'sb_s', value: await sessionFor(db, P1), url: base }]);
  await ctx.addInitScript(() => { try { localStorage.setItem('sb_ui2', '1'); } catch (e) {} });
  const p = await ctx.newPage(); p.on('pageerror', e => errors.push(e.message)); await routes(p); await routes.pinNews(p, 7); await p.goto(base + '/');
  await p.waitForSelector('.wn2-f', { timeout: 15000 }); await p.waitForTimeout(800);
  if (OUT) await p.screenshot({ path: OUT + '/tw1.png' });
  ok(await p.locator('.wn2-f video[src="/news/deduct.mp4"]').count() === 1 && /0\/1/.test(await p.textContent('.wn2-prog')), 'การ์ดหักดาว + คลิป + ลองแล้ว 0/1');
  ok(/ไว้ทีหลัง/.test(await p.textContent('#modal-content')), 'มีปุ่มปิด (ไม่บังคับลอง)');
  ok((await p.request.get(base + '/news/deduct.mp4')).ok(), 'ไฟล์คลิปโหลดได้');
  await p.click('.wn2-go'); await p.waitForSelector('.tr-tip', { timeout: 5000 }); await p.waitForTimeout(600);
  ok(/แตะการ์ดลูก/.test(await p.textContent('.tr-tip')) && !(await p.locator('.tr-next').count()), 'ขั้น 1: ต้องแตะการ์ดลูกเอง');
  if (OUT) await p.screenshot({ path: OUT + '/tw2.png' });
  await p.click('.u2-slide[data-kid]'); await p.waitForTimeout(1900);
  ok(/หักดาวอยู่ตรงนี้/.test(await p.textContent('.tr-tip')), 'ขั้น 2: ชี้ปุ่มหักดาว');
  await p.click('.kc-a.minus'); await p.waitForTimeout(1300);
  ok(/บอกเหตุผล/.test(await p.textContent('.tr-tip')), 'ขั้น 3: ช่องเหตุผล');
  await p.click('.tr-next'); await p.waitForTimeout(600); await p.click('.tr-next'); await p.waitForTimeout(700);
  ok(/ยังไม่หักจริง/.test(await p.textContent('.tr-tip')), 'ขั้นสุดท้าย: ปุ่มแดง');
  if (OUT) await p.screenshot({ path: OUT + '/tw3.png' });
  await p.fill('#dd-reason', 'ทดสอบ'); await p.fill('#dd-title', 'x');
  await p.click('#dd-go', { force: true }); await p.waitForTimeout(500);
  ok(!(await db.prepare('SELECT * FROM Deductions').first()), 'ระหว่างทัวร์ กดปุ่มแดงแล้วไม่หักจริง');
  await p.click('.tr-next'); await p.waitForTimeout(1600);
  ok(!(await p.locator('.tr-tip').count()) && !(await p.locator('.kc').count()), 'จบทัวร์ → ปิดการ์ด');
  ok(await p.locator('.wn2-done').count() === 1 && /1\/1/.test(await p.textContent('.wn2-prog')), 'กลับมามีอะไรใหม่: แสตมป์ลองแล้ว 1/1');
  if (OUT) await p.screenshot({ path: OUT + '/tw4.png' });
  await p.click('#modal-content .dq-btn.g'); await p.waitForTimeout(600);
  ok((await db.prepare('SELECT news_seen FROM Members WHERE member_id = ?').bind(P1).first()).news_seen === 7, 'จำว่าเห็นแล้ว');
  ok(!errors.length, 'ไม่มี JS error', errors);
  await br.close(); await mf.dispose(); console.log(fails ? fails + ' ไม่ผ่าน' : 'ผ่านทั้งหมด'); process.exit(fails ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
